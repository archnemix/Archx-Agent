//! Purpose: Inspects initial random-filled (`step = 0`) Transformer tensors, computes canonical SHA-256 weight digests, and exports full Settings + Hardware Provenance + optional `genesis_step0.safetensors` bundles.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use candle_core::Device;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::config::RunConfig;
use crate::hardware::{HardwareProfile, OptimizationPlan, OptimizationPlanSummary};
use crate::tokenizer::LabTokenizer;
use crate::transformer::TransformerModel;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GenesisTensorStat {
    pub name: String,
    pub shape: Vec<usize>,
    pub params: usize,
    pub mean: f32,
    pub std: f32,
    pub min: f32,
    pub max: f32,
    pub l2_norm: f32,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GenesisStateReport {
    pub sha256_hex: String,
    pub source_label: String,
    pub prng_label: String,
    pub effective_weight_seed: u64,
    pub total_tensors: usize,
    pub total_params: usize,
    pub global_mean: f32,
    pub global_std: f32,
    pub global_min: f32,
    pub global_max: f32,
    pub first_16_embedding_floats: Vec<f32>,
    pub tensor_stats: Vec<GenesisTensorStat>,
    pub exported_provenance_path: Option<PathBuf>,
    pub exported_plan_path: Option<PathBuf>,
    pub exported_genesis_safetensors_path: Option<PathBuf>,
}

/// Complete portable provenance record combining all training settings, hardware specs,
/// custom optimization plan, seed hierarchy, and initial random state fingerprint.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrainingProvenanceBundle {
    pub schema_version: String,
    pub exported_at_unix: u64,
    pub studio_version: String,
    pub run_config: RunConfig,
    pub hardware_profile: HardwareProfile,
    pub optimization_plan: OptimizationPlanSummary,
    pub tokenizer_summary: String,
    pub dataset_train_docs: usize,
    pub dataset_val_docs: usize,
    pub completed_steps: usize,
    pub best_loss: Option<f32>,
    pub genesis_weights_sha256: String,
    pub genesis_weight_source: String,
    pub genesis_first_16_floats: Vec<f32>,
    pub genesis_safetensors_filename: Option<String>,
}

/// Materializes the `step = 0` Transformer from `cfg` (honoring `seeds.genesis_reload_path` if set)
/// and inspects its exact initial random-filled weights without running any gradient step.
pub fn build_and_inspect_genesis(cfg: &RunConfig) -> Result<(TransformerModel, GenesisStateReport), String> {
    let mut m_cfg = cfg.model.sanitized();
    m_cfg.init_seed = cfg.seeds.effective_weight_seed();
    m_cfg.prng_algorithm = cfg.seeds.algorithm;

    let mut model = TransformerModel::new(&m_cfg, Device::Cpu)
        .map_err(|e| format!("Failed constructing step-0 Transformer: {e}"))?;

    let reload_trimmed = cfg.seeds.genesis_reload_path.trim();
    let source_label = if !reload_trimmed.is_empty() {
        let p = Path::new(reload_trimmed);
        model.load_weights_safetensors(p)?;
        format!("Reloaded from {}", p.display())
    } else {
        format!(
            "Generated by {} · weight_seed = {}",
            cfg.seeds.algorithm.label(),
            m_cfg.init_seed
        )
    };

    let report = inspect_varmap_genesis(
        &model,
        source_label,
        cfg.seeds.algorithm.label().to_owned(),
        m_cfg.init_seed,
    )?;
    Ok((model, report))
}

/// Computes canonical SHA-256 and distribution statistics across all `VarMap` tensors.
pub fn inspect_varmap_genesis(
    model: &TransformerModel,
    source_label: String,
    prng_label: String,
    effective_weight_seed: u64,
) -> Result<GenesisStateReport, String> {
    let map = model.varmap.data().lock().unwrap();
    let mut names: Vec<String> = map.keys().cloned().collect();
    names.sort();

    let mut hasher = Sha256::new();
    let mut total_params = 0usize;
    let mut sum = 0.0f64;
    let mut sum_sq = 0.0f64;
    let mut global_min = f32::INFINITY;
    let mut global_max = f32::NEG_INFINITY;
    let mut first_16 = Vec::new();
    let mut tensor_stats = Vec::with_capacity(names.len());

    for name in &names {
        let Some(var) = map.get(name) else {
            continue;
        };
        let t = var.as_tensor();
        let shape = t.dims().to_vec();
        let vals = t
            .flatten_all()
            .and_then(|f| f.to_vec1::<f32>())
            .map_err(|e| format!("Tensor read failed on {name}: {e}"))?;

        hasher.update((name.len() as u64).to_le_bytes());
        hasher.update(name.as_bytes());
        hasher.update((shape.len() as u64).to_le_bytes());
        for &d in &shape {
            hasher.update((d as u64).to_le_bytes());
        }
        for &v in &vals {
            hasher.update(v.to_bits().to_le_bytes());
        }

        if name == "tok_embeddings.weight" {
            first_16 = vals.iter().copied().take(16).collect();
        }

        let n = vals.len();
        total_params += n;
        let mut t_sum = 0.0f64;
        let mut t_sq = 0.0f64;
        let mut t_min = f32::INFINITY;
        let mut t_max = f32::NEG_INFINITY;
        for &v in &vals {
            let vf = f64::from(v);
            t_sum += vf;
            t_sq += vf * vf;
            if v < t_min {
                t_min = v;
            }
            if v > t_max {
                t_max = v;
            }
        }
        sum += t_sum;
        sum_sq += t_sq;
        if t_min < global_min {
            global_min = t_min;
        }
        if t_max > global_max {
            global_max = t_max;
        }

        let mean = if n > 0 { (t_sum / n as f64) as f32 } else { 0.0 };
        let var_val = if n > 0 {
            ((t_sq / n as f64) - (t_sum / n as f64).powi(2)).max(0.0)
        } else {
            0.0
        };
        if tensor_stats.len() < 18 {
            tensor_stats.push(GenesisTensorStat {
                name: name.clone(),
                shape,
                params: n,
                mean,
                std: (var_val.sqrt()) as f32,
                min: if t_min.is_finite() { t_min } else { 0.0 },
                max: if t_max.is_finite() { t_max } else { 0.0 },
                l2_norm: (t_sq.sqrt()) as f32,
            });
        }
    }

    if first_16.is_empty() {
        if let Some(first_name) = names.first() {
            if let Some(var) = map.get(first_name) {
                if let Ok(vals) = var.as_tensor().flatten_all().and_then(|f| f.to_vec1::<f32>()) {
                    first_16 = vals.into_iter().take(16).collect();
                }
            }
        }
    }

    let raw_digest: [u8; 32] = hasher.finalize().into();
    let mut sha256_hex = String::with_capacity(64);
    for b in raw_digest {
        let _ = write!(&mut sha256_hex, "{b:02x}");
    }

    let denom = total_params.max(1) as f64;
    let global_mean = (sum / denom) as f32;
    let global_var = ((sum_sq / denom) - (sum / denom).powi(2)).max(0.0);
    let global_std = (global_var.sqrt()) as f32;

    Ok(GenesisStateReport {
        sha256_hex,
        source_label,
        prng_label,
        effective_weight_seed,
        total_tensors: names.len(),
        total_params,
        global_mean,
        global_std,
        global_min: if global_min.is_finite() { global_min } else { 0.0 },
        global_max: if global_max.is_finite() { global_max } else { 0.0 },
        first_16_embedding_floats: first_16,
        tensor_stats,
        exported_provenance_path: None,
        exported_plan_path: None,
        exported_genesis_safetensors_path: None,
    })
}

/// Exports `run_provenance.json`, `optimization_plan.toml`, optional `tokenizer.json`,
/// and (when `export_genesis_safetensors` is true) `genesis_step0.safetensors` + `genesis_manifest.json`.
pub fn export_provenance_and_genesis(
    cfg: &RunConfig,
    hw: &HardwareProfile,
    plan: &OptimizationPlan,
    tokenizer: Option<&LabTokenizer>,
    train_docs: usize,
    val_docs: usize,
    completed_steps: usize,
    best_loss: Option<f32>,
    out_dir: &Path,
    export_genesis_safetensors: bool,
) -> Result<GenesisStateReport, String> {
    std::fs::create_dir_all(out_dir)
        .map_err(|_| format!("Could not create export directory {}", out_dir.display()))?;

    let (model, mut report) = build_and_inspect_genesis(cfg)?;

    let mut genesis_filename = None;
    if export_genesis_safetensors {
        let safetensors_path = out_dir.join("genesis_step0.safetensors");
        model.save_weights_safetensors(&safetensors_path)?;
        let manifest_path = out_dir.join("genesis_manifest.json");
        let manifest_bytes = serde_json::to_vec_pretty(&report)
            .map_err(|_| "Failed serializing genesis_manifest.json".to_owned())?;
        std::fs::write(&manifest_path, manifest_bytes)
            .map_err(|_| format!("Failed writing {}", manifest_path.display()))?;
        report.exported_genesis_safetensors_path = Some(safetensors_path);
        genesis_filename = Some("genesis_step0.safetensors".to_owned());
    }

    if let Some(tk) = tokenizer {
        let _ = tk.save_to_path(&out_dir.join("tokenizer.json"));
    }

    let plan_path = out_dir.join("optimization_plan.toml");
    std::fs::write(&plan_path, &plan.custom_script_toml)
        .map_err(|_| format!("Failed writing {}", plan_path.display()))?;
    report.exported_plan_path = Some(plan_path);

    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    let bundle = TrainingProvenanceBundle {
        schema_version: "archx-training-provenance-v2".to_owned(),
        exported_at_unix: now,
        studio_version: crate::VERSION.to_owned(),
        run_config: cfg.clone(),
        hardware_profile: hw.clone(),
        optimization_plan: plan.summary.clone(),
        tokenizer_summary: tokenizer
            .map(|t| t.summary().to_owned())
            .unwrap_or_else(|| cfg.tokenizer.kind.label().to_owned()),
        dataset_train_docs: train_docs,
        dataset_val_docs: val_docs,
        completed_steps,
        best_loss,
        genesis_weights_sha256: report.sha256_hex.clone(),
        genesis_weight_source: report.source_label.clone(),
        genesis_first_16_floats: report.first_16_embedding_floats.clone(),
        genesis_safetensors_filename: genesis_filename,
    };

    let prov_path = out_dir.join("run_provenance.json");
    let prov_bytes = serde_json::to_vec_pretty(&bundle)
        .map_err(|_| "Failed serializing run_provenance.json".to_owned())?;
    std::fs::write(&prov_path, prov_bytes)
        .map_err(|_| format!("Failed writing {}", prov_path.display()))?;
    report.exported_provenance_path = Some(prov_path);

    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::rng::PrngAlgorithm;

    #[test]
    fn genesis_sha256_is_deterministic_and_provenance_bundle_exports_cleanly() {
        let mut cfg = RunConfig::default();
        cfg.model.vocab_size = 128;
        cfg.model.d_model = 32;
        cfg.model.n_heads = 4;
        cfg.model.n_kv_heads = 2;
        cfg.model.n_layers = 2;
        cfg.model.d_ff = 64;
        cfg.seeds.master_seed = 777;
        cfg.seeds.algorithm = PrngAlgorithm::ChaCha8Stream;
        cfg.seeds.sync_from_master();

        let (_, rep1) = build_and_inspect_genesis(&cfg).expect("genesis 1");
        let (_, rep2) = build_and_inspect_genesis(&cfg).expect("genesis 2");
        assert_eq!(rep1.sha256_hex, rep2.sha256_hex);
        assert_eq!(rep1.first_16_embedding_floats.len(), 16);

        let hw = HardwareProfile::snapshot_fixture();
        let plan = OptimizationPlan::compile(&hw, &cfg);
        let dir = std::env::temp_dir().join(format!("archx-repro-{}", std::process::id()));
        let exported = export_provenance_and_genesis(
            &cfg,
            &hw,
            &plan,
            None,
            10,
            2,
            0,
            None,
            &dir,
            true,
        )
        .expect("export bundle");

        assert!(exported.exported_provenance_path.as_ref().unwrap().is_file());
        assert!(exported.exported_plan_path.as_ref().unwrap().is_file());
        let genesis_path = exported
            .exported_genesis_safetensors_path
            .as_ref()
            .unwrap()
            .clone();
        assert!(genesis_path.is_file());

        // Reloading that exported genesis_step0.safetensors under a DIFFERENT seed must yield the exact same SHA-256!
        let mut cfg_different_seed = cfg.clone();
        cfg_different_seed.seeds.master_seed = 123_456;
        cfg_different_seed.seeds.sync_from_master();
        cfg_different_seed.seeds.genesis_reload_path = genesis_path.to_string_lossy().into_owned();
        let (_, rep_reloaded) =
            build_and_inspect_genesis(&cfg_different_seed).expect("reloaded genesis");
        assert_eq!(rep_reloaded.sha256_hex, rep1.sha256_hex);

        let _ = std::fs::remove_dir_all(dir);
    }
}
