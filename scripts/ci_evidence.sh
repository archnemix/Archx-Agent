#!/usr/bin/env bash
# Rebuild docs/ci/ from a run the workflow published to the ci-logs branch.
#
# The workflow pushes every step's log to `ci/runs/<id>/` on `ci-logs`. Reading that branch needs
# only `contents: read`, so this script is how the evidence in `docs/ci/` gets here - by hand it
# was assembled once and drifted; generated, the numbers in the README are the numbers in the log.
#
#   ./scripts/ci_evidence.sh                 # the newest published run
#   ./scripts/ci_evidence.sh <run-id>        # a particular one
#   ./scripts/ci_evidence.sh --list          # what is available
#
# It writes: docs/ci/{status.tsv,meta.tsv,model-proof.json,tunnel-url.txt,README.md} and appends
# a row to docs/ci/RUNS.tsv, which is the history the README's table is built from.
set -eu

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BRANCH="${CI_LOG_BRANCH:-ci-logs}"
REMOTE="${CI_LOG_REMOTE:-origin}"
OUT="$HERE/docs/ci"

git -C "$HERE" fetch -q "$REMOTE" "$BRANCH"

if [ "${1:-}" = "--list" ]; then
  printf 'runs on %s/%s (newest last):\n' "$REMOTE" "$BRANCH"
  git -C "$HERE" ls-tree --name-only FETCH_HEAD ci/runs/ | sed 's#ci/runs/#  #' | sort
  exit 0
fi

ID="${1:-}"
if [ -z "$ID" ]; then
  ID="$(git -C "$HERE" ls-tree --name-only FETCH_HEAD ci/runs/ | sed 's#ci/runs/##' | sort | tail -1)"
fi
[ -n "$ID" ] || { printf 'no runs on %s/%s yet\n' "$REMOTE" "$BRANCH" >&2; exit 3; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git -C "$HERE" archive FETCH_HEAD "ci/runs/$ID" | tar -x -C "$tmp"
run="$tmp/ci/runs/$ID"
[ -f "$run/status.tsv" ] || { printf 'run %s has no status.tsv\n' "$ID" >&2; exit 4; }
mkdir -p "$OUT"

# -- artefacts, verbatim -------------------------------------------------------------------
for f in status.tsv meta.tsv model-proof.json tunnel-url.txt; do
  [ -f "$run/$f" ] && cp "$run/$f" "$OUT/$f"
done

# -- the numbers, read out of the logs rather than retyped --------------------------------
counts() { # counts <file-glob> -> "1384 passed in 372.08s" or "-"
  local line
  line="$(cat "$run"/$1 2>/dev/null | grep -Eo '[0-9]+ (passed|failed)[^=]*in [0-9.]+s' | tail -1 || true)"
  printf '%s' "${line:--}"
}
pytest_line="$(counts '0*-pytest.log')"
se_line="$(counts '0*-stress-edge.log')"
it_line="$(counts '0*-integration.log')"
failed="$(awk -F'\t' '$2 ~ /^(ok|FAIL)/ && $2 != "ok" {n++} END {print n+0}' "$run/status.tsv")"
steps="$(awk -F'\t' '$2 ~ /^(ok|FAIL)/ {n++} END {print n+0}' "$run/status.tsv")"
started="$(awk -F'\t' '$1=="started"{print $2}' "$run/meta.tsv" 2>/dev/null || true)"
commit="$(awk -F'\t' '$1=="commit"{print $2}' "$run/meta.tsv" 2>/dev/null || true)"

# -- history -------------------------------------------------------------------------------
touch "$OUT/RUNS.tsv"
if ! grep -q "^$ID" "$OUT/RUNS.tsv" 2>/dev/null; then
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$ID" "${commit:0:7}" "$steps" "$failed" "$pytest_line" "$se_line $it_line" "${started:--}" \
    >> "$OUT/RUNS.tsv"
fi

# -- README --------------------------------------------------------------------------------
{
  cat <<'HEAD'
# The CI runs that prove this, kept in the repository

Everything here came from a file-triggered GitHub Actions run - editing `.ci/trigger` and
pushing. No Actions API call is needed to start or to read it.

This file is generated by `scripts/ci_evidence.sh <run-id>` from the logs the workflow pushed to
the `ci-logs` branch. The numbers below are lifted out of those logs; nothing here is retyped.

| run | commit | steps | failed | pytest on the runner | other suites |
|-----|--------|-------|--------|----------------------|--------------|
HEAD
  awk -F'\t' '{printf "| `%s` | `%s` | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6}' "$OUT/RUNS.tsv"

  cat <<'HEAD2'

Runs #1 and #2 are the interesting failures: #1 hung on the `serve` step for nine minutes (a
backgrounded server held the step's pipe open), and #2 never started a job at all because GitHub
rejected the workflow file (`'concurrency' is already defined`) that every local YAML reader
accepted.

```bash
./scripts/ci_logs.sh --list
./scripts/ci_logs.sh --run <id>
./scripts/ci_evidence.sh <id>          # rebuild this folder from that run
git fetch origin ci-logs && git show FETCH_HEAD:ci/runs/<id>/console.log
```

HEAD2

  printf '## Status, run `%s`\n\n```text\n' "$ID"
  printf '%-14s %-8s %s\n' step status seconds
  awk -F'\t' '$2 ~ /^(ok|FAIL)/ {printf "%-12s %-8s %s\n", $1, $2, $3}' "$run/status.tsv"
  printf '```\n'

  if [ -f "$run/11-completion.log" ]; then
    printf '\n## A real model, on a CPU runner\n\n`docs/ci/model-proof.json`:\n\n```json\n'
    cat "$OUT/model-proof.json"
    printf '```\n'
  fi

  # The interesting part of a matrix log is the block between these two markers: the per-client
  # answers. The rest of the file is the setup that produced them.
  matrix() { # matrix <log> <start-marker>
    awk -v start="$2" 'index($0, start) {on=1} on && /^### and through Archx/ {exit} on' "$1" \
      | cut -c1-200
  }
  for pair in "sdk-matrix:Every official client against that endpoint" \
              "ollama:A real Ollama daemon, its own client, and the app"; do
    step="${pair%%:*}"; title="${pair#*:}"
    log="$(ls "$run"/*-"$step".log 2>/dev/null | head -1 || true)"
    [ -n "$log" ] || continue
    body="$(matrix "$log" '### the same endpoint through each official SDK')"
    [ -n "$body" ] || body="$(tail -n 30 "$log" | cut -c1-200)"
    printf '\n## %s\n\n```text\n%s\n```\n' "$title" "$body"
  done
  tunnel_log="$(ls "$run"/*-tunnel.log 2>/dev/null | head -1 || true)"
  if [ -f "$OUT/tunnel-url.txt" ]; then
    printf '\n## A public URL\n\n'
    if [ -n "$tunnel_log" ]; then
      # the last lines are the proof: the url, the HTTP status, and a vendor SDK's answer
      printf '```text\n%s\n```\n' "$(tail -n 6 "$tunnel_log" | cut -c1-200)"
    else
      printf '```text\n%s\n```\n' "$(cut -c1-200 "$OUT/tunnel-url.txt")"
    fi
  fi

  printf '\n## How long each step took\n\n'
  awk -F'\t' '$2 ~ /^(ok|FAIL)/ && $3+0 > 0 {printf "* %s: %s s\n", $1, $3}' "$run/status.tsv"
} > "$OUT/README.md"

printf 'wrote docs/ci/ from %s: %s step(s), %s failed\n' "$ID" "$steps" "$failed"
printf '  pytest      %s\n  stress/edge %s\n  integration %s\n' "$pytest_line" "$se_line" "$it_line"
